"""Require frozen benchmark parity or improvement before promoting a candidate.

Offline comparison of two results generated by scripts/eval_competitor_analogs.py.
Do not commit either GOLD-bearing input report or the case-level output.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def compare_reports(baseline: dict, candidate: dict, expected_cases: int = 100) -> dict:
    before = baseline.get("cases") or []
    after = candidate.get("cases") or []
    if len(before) != expected_cases or len(after) != expected_cases:
        raise ValueError(f"Expected {expected_cases} cases in each report; got {len(before)}, {len(after)}")
    if (baseline.get("dataset_source") != candidate.get("dataset_source")
            or baseline.get("dataset_source") is None):
        raise ValueError("Reports must use the same frozen mapping / dataset source")

    def index(rows):
        result = {}
        for row in rows:
            query = row.get("query")
            if not query or query in result:
                raise ValueError("Empty/duplicate query in benchmark")
            result[query] = row
        return result

    originals, trials = index(before), index(after)
    if set(originals) != set(trials):
        raise ValueError("Benchmark query cohort differs between runs")
    improved, regressed = [], []
    baseline_pass = candidate_pass = 0
    for query, old in originals.items():
        new = trials[query]
        if (set(old.get("acceptable_ld_ids") or [])
                != set(new.get("acceptable_ld_ids") or [])):
            raise ValueError("GOLD mapping changed between runs; results cannot be compared")
        old_ok = old.get("verdict") == "PASS"
        new_ok = new.get("verdict") == "PASS"
        baseline_pass += old_ok
        candidate_pass += new_ok
        if old_ok and not new_ok:
            regressed.append(query)
        if new_ok and not old_ok:
            improved.append(query)

    summary_before = baseline.get("summary") or {}
    summary_after = candidate.get("summary") or {}
    if (summary_before.get("evaluated_queries") != expected_cases
            or summary_after.get("evaluated_queries") != expected_cases):
        raise ValueError("Summary reports do not match requested benchmark size")
    result = {
        "cases": expected_cases,
        "baseline_pass": baseline_pass,
        "candidate_pass": candidate_pass,
        "baseline_top1": round(baseline_pass / expected_cases, 4),
        "candidate_top1": round(candidate_pass / expected_cases, 4),
        "gain": candidate_pass - baseline_pass,
        "newly_passing_count": len(improved),
        "regressed_count": len(regressed),
        "improved_queries": improved,
        "regressed_queries": regressed,
        "no_metric_drop": candidate_pass >= baseline_pass,
        "no_case_regressions": not regressed,
    }
    return result


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--baseline", type=Path, required=True)
    ap.add_argument("--candidate", type=Path, required=True)
    ap.add_argument("--expected-cases", type=int, default=100)
    ap.add_argument("--require-no-case-regressions", action="store_true",
                    help="In addition to the aggregate rate, require zero PASS→FAIL cases")
    ap.add_argument("--out", type=Path, default=Path(".tmp/frozen100_comparison.json"))
    args = ap.parse_args()
    before = json.loads(args.baseline.read_text(encoding="utf-8"))
    after = json.loads(args.candidate.read_text(encoding="utf-8"))
    result = compare_reports(before, after, expected_cases=args.expected_cases)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    # Print only counts to avoid exposing query text/labels in CI logs.
    for key, value in result.items():
        if key not in ("improved_queries", "regressed_queries"):
            print(f"{key}: {value}")
    if not result["no_metric_drop"]:
        raise SystemExit("REJECT: candidate top-1 declined on frozen cohort")
    if args.require_no_case_regressions and not result["no_case_regressions"]:
        raise SystemExit("REJECT: previously passing cases regressed")
    print("PASS: frozen benchmark quality gate")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
